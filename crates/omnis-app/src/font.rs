/// One glyph as seven row bitmaps; bit 4 is the left column, bit 0 the right.
pub type Glyph = [u8; 7];

/// Parse one art string; a malformed string fails the build.
const fn parse(art: &str) -> Glyph {
    let bytes = art.as_bytes();
    assert!(
        bytes.len() == 41,
        "a glyph is 7 rows of 5 columns joined by |"
    );
    let mut rows = [0u8; 7];
    let mut row = 0;
    while row < 7 {
        let mut column = 0;
        while column < 5 {
            let byte = bytes[row * 6 + column];
            assert!(byte == b'#' || byte == b'.', "glyph art uses # and .");
            if byte == b'#' {
                rows[row] |= 1 << (4 - column);
            }
            column += 1;
        }
        assert!(
            row == 6 || bytes[row * 6 + 5] == b'|',
            "rows are separated by |"
        );
        row += 1;
    }
    rows
}

const fn parse_all() -> [Glyph; COUNT] {
    let mut table = [[0u8; 7]; COUNT];
    let mut i = 0;
    while i < COUNT {
        table[i] = parse(ART[i]);
        i += 1;
    }
    table
}

const TABLE: [Glyph; COUNT] = parse_all();

/// The character a glyph is drawn for: itself when printable ASCII, otherwise `?`.
#[must_use]
pub const fn printable(c: char) -> char {
    if c >= FIRST && c <= LAST { c } else { '?' }
}

/// The glyph's index in the table.
#[must_use]
pub const fn index(c: char) -> usize {
    printable(c) as usize - FIRST as usize
}

/// The glyph for a character; unknown characters draw as `?`.
#[must_use]
pub fn glyph(c: char) -> &'static Glyph {
    &TABLE[index(c)]
}

/// Whether the glyph has ink at `(column, row)`.
#[must_use]
pub fn ink(glyph: &Glyph, column: i32, row: i32) -> bool {
    (0..GLYPH_WIDTH).contains(&column)
        && (0..GLYPH_HEIGHT).contains(&row)
        && glyph[row as usize] & (1 << (GLYPH_WIDTH - 1 - column)) != 0
}

/// The first `cells` characters of the text with every non-printable character as `?`.
#[must_use]
pub fn fit(text: &str, cells: usize) -> String {
    text.chars().take(cells).map(printable).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_seven_rows_of_five_columns() {
        for (i, art) in ART.iter().enumerate() {
            let rows: Vec<&str> = art.split('|').collect();
            assert_eq!(rows.len(), 7, "glyph {i}");
            for row in rows {
                assert_eq!(row.len(), 5, "glyph {i}");
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "glyph {i}");
            }
            assert!(TABLE[i].iter().all(|row| *row < 32), "glyph {i}");
        }
    }

    #[test]
    fn known_glyphs_have_the_expected_bitmaps() {
        assert_eq!(
            glyph('A'),
            &[
                0b01110, 0b10001, 0b10001, 0b11111, 0b10001, 0b10001, 0b10001
            ]
        );
        assert_eq!(glyph('.'), &[0, 0, 0, 0, 0, 0b01100, 0b01100]);
        assert_eq!(glyph(' '), &[0; 7]);
        assert!(ink(glyph('A'), 0, 1) && !ink(glyph('A'), 0, 0));
        assert!(!ink(glyph('A'), 5, 1) && !ink(glyph('A'), 0, 7));
    }

    #[test]
    fn no_two_glyphs_are_alike() {
        for (i, a) in TABLE.iter().enumerate() {
            for (j, b) in TABLE.iter().enumerate().skip(i + 1) {
                assert_ne!(a, b, "glyphs {i} and {j} are identical");
            }
        }
    }

    #[test]
    fn unknown_characters_draw_as_question_marks() {
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
        assert_eq!(index('~'), COUNT - 1);
        assert_eq!(fit("Ægir the Bold", 7), "?gir th");
        assert_eq!(fit("", 5), "");
        assert_eq!(fit("ab", 5), "ab");
    }
}
